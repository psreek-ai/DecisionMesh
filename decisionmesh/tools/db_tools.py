# ── Tool Execution Functions ──────────────────────────────────────────────────
# These are called by agents during their tool-use loops.

async def db_get_decision(decision_id: str, db_session) -> dict:
    """Fetch decision with premises from DB."""
    from sqlalchemy import select
    from decisionmesh.models.decision import DecisionORM
    from decisionmesh.models.premise import PremiseORM

    result = await db_session.execute(
        select(DecisionORM).where(DecisionORM.id == decision_id)
    )
    decision = result.scalar_one_or_none()
    if not decision:
        return {"error": f"Decision {decision_id} not found"}

    premises_result = await db_session.execute(
        select(PremiseORM).where(PremiseORM.decision_id == decision_id)
    )
    premises = premises_result.scalars().all()

    d = decision.to_pydantic().model_dump(mode="json")
    d["premises_detail"] = [p.to_pydantic().model_dump(mode="json") for p in premises]
    return d


async def db_get_premises(decision_id: str, db_session) -> list[dict]:
    from sqlalchemy import select
    from decisionmesh.models.premise import PremiseORM

    result = await db_session.execute(
        select(PremiseORM).where(PremiseORM.decision_id == decision_id)
    )
    return [p.to_pydantic().model_dump(mode="json") for p in result.scalars().all()]


async def db_get_prior_observations(premise_id: str, limit: int, db_session) -> list[dict]:
    from sqlalchemy import select, desc
    from decisionmesh.models.observation import ObservationORM

    result = await db_session.execute(
        select(ObservationORM)
        .where(ObservationORM.premise_id == premise_id)
        .order_by(desc(ObservationORM.observed_at))
        .limit(limit)
    )
    return [o.to_pydantic().model_dump(mode="json") for o in result.scalars().all()]


async def db_save_observation(data: SaveObservationInput, db_session) -> dict:
    from decisionmesh.models.observation import ObservationORM

    obs = ObservationORM(
        decision_id=data.decision_id,
        premise_id=data.premise_id,
        observation_text=data.observation_text,
        source_urls=data.source_urls,
        relevance_score=data.relevance_score,
        supports_premise=data.supports_premise,
        agent_reasoning=data.agent_reasoning,
    )
    db_session.add(obs)
    await db_session.flush()
    return {"id": obs.id, "status": "saved"}


async def db_compute_divergence(decision_id: str, db_session) -> dict:
    from sqlalchemy import select
    from decisionmesh.models.premise import PremiseORM, PremiseStatus

    result = await db_session.execute(
        select(PremiseORM).where(PremiseORM.decision_id == decision_id)
    )
    premises = result.scalars().all()

    if not premises:
        return {"divergence_score": 0.0, "details": []}

    score_map = {
        PremiseStatus.VALID.value: 0.0,
        PremiseStatus.UNCERTAIN.value: 0.4,
        PremiseStatus.INVALIDATED.value: 1.0,
        PremiseStatus.UNVERIFIABLE.value: 0.2,
    }

    weighted_sum = 0.0
    total_weight = 0.0
    details = []
    for p in premises:
        invalidation_score = score_map.get(p.status, 0.0)
        weighted_sum += p.weight * invalidation_score
        total_weight += p.weight
        details.append({
            "premise_id": p.id,
            "text": p.text[:100],
            "status": p.status,
            "weight": p.weight,
            "invalidation_score": invalidation_score,
        })

    divergence_score = weighted_sum / total_weight if total_weight > 0 else 0.0
    return {"divergence_score": round(divergence_score, 4), "details": details}


async def db_create_divergence_event(data: CreateDivergenceEventInput, db_session) -> dict:
    from decisionmesh.models.divergence import DivergenceEventORM
    from decisionmesh.models.decision import DecisionORM, DecisionStatus

    event = DivergenceEventORM(
        decision_id=data.decision_id,
        severity=data.severity,
        affected_premise_ids=data.affected_premise_ids,
        summary=data.summary,
        evidence=data.evidence,
        divergence_score=data.divergence_score,
    )
    db_session.add(event)

    # Update decision status
    result = await db_session.execute(
        __import__("sqlalchemy", fromlist=["select"]).select(DecisionORM).where(DecisionORM.id == data.decision_id)
    )
    decision = result.scalar_one_or_none()
    if decision:
        decision.status = DecisionStatus.DRIFTED.value

    await db_session.flush()
    return {"divergence_event_id": event.id, "status": "created"}


async def db_get_all_active_decisions(limit: int, db_session) -> list[dict]:
    from sqlalchemy import select
    from decisionmesh.models.decision import DecisionORM, DecisionStatus

    result = await db_session.execute(
        select(DecisionORM)
        .where(DecisionORM.status == DecisionStatus.ACTIVE.value)
        .limit(limit)
    )
    return [d.to_pydantic().model_dump(mode="json") for d in result.scalars().all()]


