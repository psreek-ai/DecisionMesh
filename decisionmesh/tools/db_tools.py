"""
DecisionMesh — Database CRUD Tools
Tool schemas and implementations for agent DB access.
All inputs are Pydantic-validated.
"""
from typing import Optional
from pydantic import BaseModel, Field


# ── Tool Schemas ──────────────────────────────────────────────────────────────

class GetDecisionInput(BaseModel):
    decision_id: str = Field(description="The UUID of the decision to retrieve.")


class GetPremisesInput(BaseModel):
    decision_id: str = Field(description="The UUID of the decision whose premises to retrieve.")


class GetPriorObservationsInput(BaseModel):
    premise_id: str = Field(description="The UUID of the premise.")
    limit: int = Field(default=5, ge=1, le=50, description="Maximum number of prior observations to return.")


class SaveObservationInput(BaseModel):
    decision_id: str
    premise_id: str
    observation_text: str = Field(description="What the agent found when checking this premise.")
    source_urls: list[str] = Field(default_factory=list)
    relevance_score: float = Field(ge=0.0, le=1.0, description="How relevant this observation is to the premise.")
    supports_premise: Optional[bool] = Field(default=None, description="True=supports, False=contradicts, None=ambiguous.")
    agent_reasoning: str = Field(description="Full think-tool reasoning that led to this observation.")


class ComputeDivergenceInput(BaseModel):
    decision_id: str = Field(description="The decision to compute divergence score for.")


class CreateDivergenceEventInput(BaseModel):
    decision_id: str
    severity: str = Field(description="low|medium|high|critical")
    affected_premise_ids: list[str]
    summary: str = Field(description="Human-readable divergence description.")
    evidence: list[str] = Field(description="Supporting observations as text snippets.")
    divergence_score: float = Field(ge=0.0, le=1.0)


class GetAllActiveDecisionsInput(BaseModel):
    limit: int = Field(default=50, ge=1, le=200)


class SaveCounterfactualInput(BaseModel):
    decision_id: str
    divergence_event_id: str
    alternative_scenario: str
    projected_outcome_delta: str
    confidence: float = Field(ge=0.0, le=1.0)
    causal_chain: list[str] = Field(description="Step-by-step causal reasoning, each labeled KNOWN/INFERRED/SPECULATED.")
    agent_reasoning: str


class UpdateDecisionDNAInput(BaseModel):
    decision_id: str
    field: str = Field(description="Field to update: premises|predicted_outcomes|triggering_conditions|status|domain|tags")
    value: str = Field(description="New value as JSON string for list fields, or plain string for string fields.")


class CloseDecisionInput(BaseModel):
    decision_id: str
    reason: str = Field(description="Why the decision is being closed.")


class PauseMonitoringInput(BaseModel):
    decision_id: str
    pause: bool = Field(description="True to pause, False to resume monitoring.")


